import { useMemo } from 'react'
import { create } from 'zustand'
import { persist } from 'zustand/middleware'

export type Lang = 'en' | 'pt'

/** Portuguese (Brazil) is the default; only an explicitly English browser flips to en. */
function detectLang(): Lang {
  if (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('en')) return 'en'
  return 'pt'
}

type LangState = { lang: Lang; setLang: (l: Lang) => void; toggle: () => void }

export const useLang = create<LangState>()(
  persist(
    (set, get) => ({
      lang: detectLang(),
      setLang: (lang) => set({ lang }),
      toggle: () => set({ lang: get().lang === 'en' ? 'pt' : 'en' }),
    }),
    { name: 'pelada-lang' },
  ),
)

/** Read the active language outside React (canvas share image, date formatting). */
export function getLang(): Lang {
  return useLang.getState().lang
}

type Dict = Record<string, string>

function interpolate(str: string, params?: Record<string, string | number>): string {
  if (!params) return str
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`))
}

export type TFn = (key: string, params?: Record<string, string | number>) => string

function makeT(lang: Lang): TFn {
  const table = DICT[lang]
  return (key, params) => interpolate(table[key] ?? DICT.en[key] ?? key, params)
}

/** Hook for components — re-renders when the language changes. */
export function useT(): TFn {
  const lang = useLang((s) => s.lang)
  return useMemo(() => makeT(lang), [lang])
}

/** Static translator for non-React callers (share.ts). */
export function t(key: string, params?: Record<string, string | number>): string {
  return makeT(getLang())(key, params)
}

/** Pick singular/plural variant: looks up `${base}.one` / `${base}.other`. */
export function plural(tf: TFn, base: string, n: number, params?: Record<string, string | number>): string {
  return tf(`${base}.${n === 1 ? 'one' : 'other'}`, { n, ...params })
}

